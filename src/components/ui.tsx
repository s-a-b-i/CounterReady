"use client";

import { motion, useMotionValue, useReducedMotion, useSpring } from "framer-motion";
import { useRef, type ReactNode } from "react";

/** Staggered reveal on scroll. */
export function Reveal({ children, delay = 0, className = "" }: { children: ReactNode; delay?: number; className?: string }) {
  const reduce = useReducedMotion();
  return (
    <motion.div
      className={className}
      initial={reduce ? false : { opacity: 0, y: 24 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-60px" }}
      transition={{ duration: 0.7, delay, ease: [0.22, 1, 0.36, 1] }}
    >
      {children}
    </motion.div>
  );
}

/** Button that leans toward the pointer. */
export function Magnetic({ children, className = "" }: { children: ReactNode; className?: string }) {
  const reduce = useReducedMotion();
  const ref = useRef<HTMLDivElement>(null);
  const x = useSpring(useMotionValue(0), { stiffness: 220, damping: 18 });
  const y = useSpring(useMotionValue(0), { stiffness: 220, damping: 18 });
  return (
    <motion.div
      ref={ref}
      className={`inline-block ${className}`}
      style={{ x, y }}
      onMouseMove={(e) => {
        if (reduce || !ref.current) return;
        const r = ref.current.getBoundingClientRect();
        x.set((e.clientX - (r.left + r.width / 2)) * 0.25);
        y.set((e.clientY - (r.top + r.height / 2)) * 0.25);
      }}
      onMouseLeave={() => { x.set(0); y.set(0); }}
    >
      {children}
    </motion.div>
  );
}

export type ImageLabel = "AI preview" | "Pre-generated example" | "Catalogue photo";

/** Every image carries an honest provenance label. */
export function Label({ kind, className = "" }: { kind: ImageLabel; className?: string }) {
  return (
    <span
      className={`inline-flex items-center rounded-full bg-ink/85 text-bg px-2.5 py-1 text-[0.68rem] font-semibold tracking-wide backdrop-blur ${className}`}
    >
      {kind}
    </span>
  );
}

export function Source({ kind }: { kind: "youcam" | "catalogue" | "smallprint" }) {
  const map = {
    youcam: ["Generated by YouCam", "bg-maybebg text-goldtext"],
    catalogue: ["From the seller's catalogue", "bg-sunk text-soft"],
    smallprint: ["Computed by SmallPrint", "bg-sagebg text-sage"],
  } as const;
  return <span className={`inline-block rounded-full px-2.5 py-0.5 text-[0.68rem] font-semibold ${map[kind][1]}`}>{map[kind][0]}</span>;
}

/** Vertical to-scale ruler: 1 cm = `pxPerCm` pixels. */
export function Ruler({ cm, pxPerCm = 14, color = "var(--gold)" }: { cm: number; pxPerCm?: number; color?: string }) {
  const h = Math.max(cm * pxPerCm, 8);
  const ticks = Array.from({ length: Math.floor(cm) + 1 }, (_, i) => i);
  return (
    <svg width="46" height={h + 18} viewBox={`0 0 46 ${h + 18}`} role="img" aria-label={`${cm} centimetre drop, drawn to scale`}>
      <rect x="0" y="4" width="10" height={h} rx="5" fill={color} opacity="0.9" />
      {ticks.map((t) => (
        <g key={t}>
          <line x1="20" x2={t % 5 === 0 ? 34 : 28} y1={4 + t * pxPerCm} y2={4 + t * pxPerCm} stroke="var(--ink-soft)" strokeWidth="1" />
          {t % 5 === 0 && t > 0 && <text x="36" y={8 + t * pxPerCm} fontSize="9" fill="var(--ink-soft)" fontFamily="var(--font-num)">{t}</text>}
        </g>
      ))}
      <line x1="20" x2="20" y1="4" y2={4 + h} stroke="var(--ink-soft)" strokeWidth="1" />
      <text x="0" y={h + 16} fontSize="9" fill="var(--ink)" fontFamily="var(--font-num)">{cm}cm</text>
    </svg>
  );
}

/** Grams compared with everyday items. */
export function WeightMeter({ grams }: { grams: number }) {
  const max = 25;
  const pct = Math.min(grams / max, 1) * 100;
  const refs = [{ l: "paperclip", g: 1 }, { l: "grape", g: 5 }, { l: "AA battery", g: 23 }];
  return (
    <div>
      <div className="relative h-2 rounded-full bg-sunk" role="img" aria-label={`${grams} grams`}>
        <div className="absolute inset-y-0 left-0 rounded-full bg-gold" style={{ width: `${pct}%` }} />
        {refs.map((r) => (
          <span key={r.l} className="absolute top-1/2 h-3 w-px -translate-y-1/2 bg-ink/40" style={{ left: `${(r.g / max) * 100}%` }} />
        ))}
      </div>
      <div className="relative mt-1 h-4 text-[0.65rem] text-soft">
        {refs.map((r) => (
          <span key={r.l} className="absolute -translate-x-1/2 whitespace-nowrap" style={{ left: `${Math.min((r.g / max) * 100, 92)}%` }}>{r.l}</span>
        ))}
      </div>
    </div>
  );
}
